/* knc-c-gen.c: writes knc.c, Intel-Phi-3120A's libknc (card/lib/knc, the
 * kernels knc-mvex-gen writes as .byte lines) in C with the Knights Corner
 * intrinsics: the same functions, tables and contracts (knc.h). The S3 gate
 * links both into one binary (knc-gate.c). A generator, as knc-mvex-gen is,
 * because a shift count must be a constant expression: every position and
 * word is written out with its numbers. See README.md.
 *
 *   knc-c-gen > knc.c */
#include <stdio.h>

static void unpack_body(int b, int kind) /* 0 plain, 1 for, 2 delta */
{
	printf("\tconst __m512i mask = _mm512_set1_epi32(%d);\n", b == 32 ? -1 : (int)((1u << b) - 1));
	if (kind == 1) printf("\tconst __m512i bv = _mm512_load_epi32(base);\n");
	if (kind == 2) printf("\t__m512i acc = _mm512_load_epi32(base);\n");
	for (int p = 0; p < 64; p++) {
		int s = p * b % 32, w = p * b / 32;
		printf("\t{\n\t\t__m512i v = _mm512_load_epi32(packed + %d);\n", 16 * w);
		if (s) printf("\t\tv = _mm512_srli_epi32(v, %d);\n", s);
		if (s + b > 32)
			printf("\t\tv = _mm512_or_epi32(v, _mm512_slli_epi32(_mm512_load_epi32(packed + %d), %d));\n", 16 * (w + 1), 32 - s);
		if (s + b != 32) printf("\t\tv = _mm512_and_epi32(v, mask);\n");
		if (kind == 1) printf("\t\tv = _mm512_add_epi32(v, bv);\n");
		if (kind == 2) printf("\t\tacc = _mm512_add_epi32(acc, v);\n\t\tv = acc;\n");
		printf("\t\t_mm512_store_epi32(out + %d, v);\n\t}\n", 16 * p);
	}
}

static void pack_body(int b)
{
	if (b < 32) printf("\tconst __m512i mask = _mm512_set1_epi32(%d);\n", (int)((1u << b) - 1));
	for (int w = 0; w < 2 * b; w++) {
		int first = 1;
		printf("\t{\n\t\t__m512i acc;\n");
		for (int p = 0; p < 64; p++) {
			int lo = p * b, hi = p * b + b; /* bits [lo, hi) of the lane stream */
			int starts = lo / 32 == w, crosses = lo / 32 == w - 1 && hi > 32 * w;
			if (!starts && !crosses) continue;
			/* the value, masked to b bits (all 32 need no mask), then shifted
			 * into place; the first one starts the word, the rest are ORed */
			char v[96];
			snprintf(v, sizeof v, b < 32 ? "_mm512_and_epi32(_mm512_load_epi32(values + %d), mask)" : "_mm512_load_epi32(values + %d)", 16 * p);
			char t[160];
			if (starts) {
				if (lo % 32) snprintf(t, sizeof t, "_mm512_slli_epi32(%s, %d)", v, lo % 32);
				else snprintf(t, sizeof t, "%s", v);
			} else
				snprintf(t, sizeof t, "_mm512_srli_epi32(%s, %d)", v, 32 - lo % 32);
			if (first) printf("\t\tacc = %s;\n", t);
			else printf("\t\tacc = _mm512_or_epi32(acc, %s);\n", t);
			first = 0;
		}
		printf("\t\t_mm512_store_epi32(packed + %d, acc);\n\t}\n", 16 * w);
	}
}

/* FastLanes: a row of 32 words, two halves of 16 lanes; in is 4-byte aligned */
static void fls_body(int b)
{
	printf("\tconst __m512i bv = _mm512_extload_epi32(base, _MM_UPCONV_EPI32_NONE, _MM_BROADCAST_1X16, _MM_HINT_NONE);\n");
	if (b) printf("\tconst __m512i mask = _mm512_set1_epi32(%d);\n", b == 32 ? -1 : (int)((1u << b) - 1));
	for (int h = 0; h < 2; h++)
		for (int p = 0; p < 32; p++) {
			int s = p * b % 32, w = p * b / 32;
			if (!b) {
				printf("\t_mm512_store_epi32(out + %d, bv);\n", 32 * p + 16 * h);
				continue;
			}
			printf("\t{\n\t\t__m512i v = KNC_ULOAD(in + %d);\n", 32 * w + 16 * h);
			if (s) printf("\t\tv = _mm512_srli_epi32(v, %d);\n", s);
			if (s + b > 32) printf("\t\tv = _mm512_or_epi32(v, _mm512_slli_epi32(KNC_ULOAD(in + %d), %d));\n", 32 * (w + 1) + 16 * h, 32 - s);
			if (s + b != 32) printf("\t\tv = _mm512_and_epi32(v, mask);\n");
			printf("\t\t_mm512_store_epi32(out + %d, _mm512_add_epi32(v, bv));\n\t}\n", 32 * p + 16 * h);
		}
}

int main(void)
{
	printf("/* knc.c: generated by tests/s3/knc-c-gen.c. Do not edit by hand.\n"
	       " * Intel-Phi-3120A's libknc in C with the Knights Corner intrinsics; the\n"
	       " * contracts are knc.h's. The pointers do not overlap (restrict). */\n"
	       "#include <immintrin.h>\n#include <stddef.h>\n\n"
	       "/* an unaligned 64-byte load: the lo half up to the line end, the hi half from it */\n"
	       "#define KNC_ULOAD(p) _mm512_loadunpackhi_epi32(_mm512_loadunpacklo_epi32(_mm512_undefined_epi32(), (p)), (p) + 16)\n\n");
	static const char *kinds[3] = {"unpack", "unpack_for", "unpack_delta"};
	for (int k = 0; k < 3; k++)
		for (int b = 1; b <= 32; b++) {
			printf("void knc_%s_b%d(int *restrict out, const unsigned *restrict packed%s)\n{\n", kinds[k], b,
			       k ? ", const int *restrict base" : "");
			unpack_body(b, k);
			printf("}\n\n");
		}
	for (int b = 1; b <= 32; b++) {
		printf("void knc_pack_b%d(unsigned *restrict packed, const int *restrict values)\n{\n", b);
		pack_body(b);
		printf("}\n\n");
	}
	printf("void knc_encode_for(int *restrict out, const int *restrict values, const int *restrict base)\n{\n"
	       "\tconst __m512i bv = _mm512_load_epi32(base);\n");
	for (int p = 0; p < 64; p++)
		printf("\t_mm512_store_epi32(out + %d, _mm512_sub_epi32(_mm512_load_epi32(values + %d), bv));\n", 16 * p, 16 * p);
	printf("}\n\nvoid knc_encode_delta(int *restrict out, const int *restrict values, const int *restrict base)\n{\n"
	       "\t__m512i prev = _mm512_load_epi32(base), v;\n");
	for (int p = 0; p < 64; p++)
		printf("\tv = _mm512_load_epi32(values + %d);\n\t_mm512_store_epi32(out + %d, _mm512_sub_epi32(v, prev));\n\tprev = v;\n",
		       16 * p, 16 * p);
	printf("}\n\n");
	for (int b = 0; b <= 32; b++) {
		printf("void knc_fls_unffor_b%d(const unsigned *restrict in, unsigned *restrict out, const unsigned *restrict base)\n{\n", b);
		if (!b) printf("\t(void)in;\n");
		fls_body(b);
		printf("}\n\n");
	}
	/* the tables and the dispatch (a width outside the range touches nothing) */
	static const char *tabs[4] = {"unpack", "pack", "unpack_for", "unpack_delta"};
	static const char *types[4] = {"knc_unpack_fn", "knc_pack_fn", "knc_unpack_base_fn", "knc_unpack_base_fn"};
	printf("typedef void (*knc_unpack_fn)(int *, const unsigned *);\n"
	       "typedef void (*knc_pack_fn)(unsigned *, const int *);\n"
	       "typedef void (*knc_unpack_base_fn)(int *, const unsigned *, const int *);\n"
	       "typedef void (*knc_fls_unffor_fn)(const unsigned *, unsigned *, const unsigned *);\n\n");
	for (int t = 0; t < 4; t++) {
		printf("const %s knc_%s_table[33] = {0", types[t], tabs[t]);
		for (int b = 1; b <= 32; b++) printf(", knc_%s_b%d", tabs[t], b);
		printf("};\n");
	}
	printf("const knc_fls_unffor_fn knc_fls_unffor_table[33] = {knc_fls_unffor_b0");
	for (int b = 1; b <= 32; b++) printf(", knc_fls_unffor_b%d", b);
	printf("};\n\n"
	       "void knc_unpack(int *out, const void *packed, unsigned bits)\n{\n\tif (bits - 1 < 32) knc_unpack_table[bits](out, packed);\n}\n"
	       "void knc_pack(void *packed, const int *values, unsigned bits)\n{\n\tif (bits - 1 < 32) knc_pack_table[bits](packed, values);\n}\n"
	       "void knc_unpack_for(int *out, const void *packed, unsigned bits, const int *base)\n{\n\tif (bits - 1 < 32) knc_unpack_for_table[bits](out, packed, base);\n}\n"
	       "void knc_unpack_delta(int *out, const void *packed, unsigned bits, const int *base)\n{\n\tif (bits - 1 < 32) knc_unpack_delta_table[bits](out, packed, base);\n}\n"
	       "void knc_fls_unffor(const unsigned *in, unsigned *out, unsigned bw, const unsigned *base)\n{\n\tif (bw <= 32) knc_fls_unffor_table[bw](in, out, base);\n}\n");
	return 0;
}
