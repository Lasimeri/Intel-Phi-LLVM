#!/usr/bin/env bash
# knc-mvex-check.sh: the stack's sanctioned MVEX encoder (knc-mvex, in the
# Intel-Phi-3120A repo) against llvm-mc. Every ".byte ... # text" line its
# generator wrote into card/examples/*.S is assembled from its text with
# llvm-mc -mcpu=knc and the bytes compared. knc-mvex always writes a 32-bit
# displacement (mod = 10), so memory forms get LLVM's {disp32} pseudo-prefix;
# nothing else is changed. See knc-mvex-check.md.
set -euo pipefail
. "$(cd "$(dirname "$0")/.." && pwd)/scripts/env.sh"
: "${LLVM_MC:?set LLVM_MC to the llvm-mc to check}"
EX="$PHI_STACK_ROOT/card/examples"
W="$llvm_build/oracle/knc-mvex"; mkdir -p "$W"
files=$(grep -l '^# .*generated by knc-mvex-gen' "$EX"/*.S)
awk '/^[ \t]*\.byte 0x/ && /#/ {
       b = $0; sub(/#.*/, "", b); sub(/^[ \t]*\.byte[ \t]*/, "", b); gsub(/0x/, "", b); gsub(/[ \t]/, "", b); gsub(/,/, " ", b)
       t = $0; sub(/^[^#]*#[ \t]*/, "", t)
       print FILENAME ":" FNR "|" b "|" t }' $files > "$W/vectors.txt"
{ echo ".intel_syntax noprefix"; awk -F'|' '{ print (index($3, "[") ? "{disp32} " : "") $3 }' "$W/vectors.txt"; } > "$W/vectors.s"
"$LLVM_MC" -triple=x86_64-unknown-linux-musl -mcpu=knc -show-encoding "$W/vectors.s" 2> "$W/mc.err" |
  awk '/# encoding:/ { match($0, /# encoding: \[[^]]*\]/); e = substr($0, RSTART + 13, RLENGTH - 14); gsub(/0x/, "", e); gsub(/,/, " ", e); print e }' > "$W/mc.bytes"
errors=$(grep -c 'error:' "$W/mc.err" || true)
paste -d'|' "$W/vectors.txt" "$W/mc.bytes" | awk -F'|' -v errors="$errors" '
  $2 != $4 { n++; if (n <= 10) printf "differ %s: %s\n  knc-mvex %s\n  llvm-mc  %s\n", $1, $3, $2, $4 }
  END { printf "knc-mvex vs llvm-mc: %d vectors (%s), %d byte mismatches, %d llvm-mc errors\n", NR, "card/examples", n + 0, errors; exit (n > 0 || errors > 0) }'
